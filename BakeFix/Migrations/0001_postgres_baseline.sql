-- ============================================================================
-- Postgres baseline migration — replaces the old MySQL-era 0001-0004 files
-- (archived under Migrations/mysql-archive/, kept for history, never run
-- again). This is a consolidated schema for the 42 in-scope BakeFix tables:
-- Group A (live BakeFix code, 28 tables) + Group B (stashed Billing /
-- RunningBalance feature, 14 tables). Group C ("MobileMend", 12 tables) was
-- excluded per user decision — a different app's data sharing the old MySQL
-- service, not part of this app.
--
-- IMPORTANT: this file is ALREADY APPLIED to the live Postgres database (it
-- is copied verbatim from postgres-migration/01_schema.sql, which was applied
-- by hand during the data migration). SchemaVersions must be pre-seeded with
-- this filename before the app's first startup against Postgres, or
-- DatabaseMigrator will try to re-run it and fail on "relation already
-- exists" (see the project's Postgres migration docs for the seed command).
-- DatabaseMigrator now wraps every migration file in its own transaction, so
-- this file intentionally has no BEGIN/COMMIT of its own (unlike the
-- original postgres-migration/01_schema.sql, meant for standalone psql use).
--
-- Hand-ported from `SHOW CREATE TABLE` output captured against the live Aiven
-- MySQL instance on 2026-11-21. Tables are created in FK-dependency order
-- (parents before children). Translation rules applied throughout:
--   - CHAR(36) GUID keys kept as-is (no type change, lowest risk)
--   - TINYINT(1)            -> BOOLEAN   (data cast 0/1 -> false/true at load time)
--   - DATETIME / TIMESTAMP  -> TIMESTAMP (naive, matches current app behavior)
--   - ENUM(...)             -> VARCHAR + CHECK (...)  (matches how the app already
--                              treats these as plain strings; avoids ALTER TYPE
--                              ceremony later)
--   - INT AUTO_INCREMENT    -> INT GENERATED BY DEFAULT AS IDENTITY
--                              (BY DEFAULT, not ALWAYS, so the data load can
--                              insert the existing source IDs; sequence is
--                              resynced after load - see 02_data_load.load)
--   - Inline KEY/INDEX      -> separate CREATE INDEX statements
--   - ON UPDATE CURRENT_TIMESTAMP -> BEFORE UPDATE trigger using set_updated_at()
--   - FULLTEXT KEY          -> generated tsvector column + GIN index
--   - DEFAULT (uuid())      -> dropped (confirmed dead: every repository always
--                              supplies @Id explicitly on INSERT)
--   - All identifiers left UNQUOTED (folds to lowercase) so the existing,
--     unquoted-PascalCase SQL text in the C# repositories keeps working
--     unchanged once the driver is swapped in Phase 3 of the code-port plan.
--     The only two columns literally named a MySQL-reserved-ish word, `Date`,
--     stay unquoted too ("date" is a safe, non-reserved identifier in Postgres).
--
-- ============================================================================


-- Each ON UPDATE CURRENT_TIMESTAMP column gets its own small trigger function
-- below, right after its table (named per-table since the column name varies).

